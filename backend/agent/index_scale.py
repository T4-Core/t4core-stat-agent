"""
[NEW 11-27] 질문이 요청한 지수 환산 방식 — 모듈 2(measure 판단)와 모듈 3(계산)이 같이 쓴다

  minmax  '최소=0·최대=100' · '0~100 지수'        비교 대상 안에서 가장 작은 값 0, 가장 큰 값 100
  mean    '평균=100' · '월평균=100'               비교 대상의 평균을 100
  None    그 밖                                   (지수가 아니거나, 기준 시점 = 100 지수)

  재작성 질문에서는 이 표현이 사라진다 ('… 조이혼율 시도별', '… 증감률'). 그래서 **원 질문**을 본다.
  레이더 20선(2026-11-26): '17개 시도 내 최소=0·최대=100 지수로 환산' 이 값 조회(raw)로, '해당 기간 내 0~100 지수로 환산' 이 증감률로 분류됐다.
"""
import re

_EQ = r"\s*값?\s*[=:은는이가]?\s*"
_MINMAX = re.compile(rf"최(?:소|솟){_EQ}0\D{{0,4}}최(?:대|댓){_EQ}100"           # 최소=0·최대=100 · 최솟값 0, 최댓값 100
                     r"|(?<![\d.])0\s*[~∼\-–]\s*100\s*(?:점\s*)?(?:사이의?\s*)?(?:지수|척도|점수|으로|로)")   # 0~100 지수 · 0~100으로
_MEAN = re.compile(r"평균\s*[=:]\s*100|평균(?:을|이|값을)?\s*100\s*(?:으로|로|인)")       # 월평균=100 · 평균을 100으로

SCALES = ("minmax", "mean")
SCALE_NAME = {"minmax": "최소=0 · 최대=100 지수", "mean": "평균=100 지수"}


def index_scale(text: str | None) -> str | None:
    """질문 문장 → 'minmax' · 'mean' · None"""
    t = str(text or "")
    if _MINMAX.search(t):
        return "minmax"
    if _MEAN.search(t):
        return "mean"
    return None
