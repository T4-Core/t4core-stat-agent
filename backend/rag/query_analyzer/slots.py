def build_hint_block(rule_found):
    """2-2 코드 추출 결과를 user 프롬프트 조각으로 (없으면 빈 문자열)"""
    if not rule_found:
        return ""
    return "[코드가 질문에서 찾은 값] 맞는 슬롯에 그대로 넣는다.\n" + \
           "\n".join(f"- {k}: {', '.join(v)}" for k, v in rule_found.items())


def wrap_question(q):
    """질문을 <question> 태그로 감쌈. 질문 안에 태그를 흉내 낸 문자열이 있으면 [question]으로 무력화"""
    safe = re.sub(r"</?\s*question\s*>", lambda m: m.group(0).replace("<", "[").replace(">", "]"), q, flags=re.I)
    return f"<question>{safe}</question>"


def build_slot_few_shot():
    lines = ["[예시] (예시는 값 있는 슬롯만 보여 준다. 실제 출력에는 모든 슬롯 키를 넣는다)"]
    for ex in SLOT_FEW_SHOT:
        user = "\n".join(p for p in [build_term_block(ex.get("terms", [])), build_hint_block(ex.get("hint", {})),
                                     wrap_question(ex["q"])] if p)
        out = {"slots": ex["slots"], "sub_questions": ex.get("sub", [])}
        lines.append(f"입력:\n{user}\n출력: {json.dumps(out, ensure_ascii=False)}")
    return "\n\n".join(lines)


